# [국립국어원 한국어 어문 규범 표준어규정 제2부 표준발음법 제3장 음의 길이]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a389


# [제6항 Norm 6]
#
# 모음의 장단을 구별하여 발음하되, 단어의 첫음절에서만 긴소리가 나타나는 것을 원칙으로 한다.
# Vowel length shall be distinguished in pronunciation, with the principle being that
# long sounds appear only in the first syllable of a word.
#
# (1) 첫음절에서 긴소리가 나는 경우 Long sounds in the first syllable:
#     눈보라[눈:보라]
#     말씨[말:씨]
#     밤나무[밤:나무]
#     많다[만:타]
#     멀리[멀:리]
#     벌리다[벌:리다]
#
# (2) 둘째 음절 이하에서 짧게 변하는 경우 Shortened in the second syllable or later:
#     첫눈[천눈]
#     참말[참말]
#     쌍동밤[쌍동밤]
#     수많이[수마니]
#     눈멀다[눈멀다]
#     떠벌리다[떠벌리다]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a389


# [제6항 다만 Proviso of Norm 6]
#
# 합성어의 경우에는 둘째 음절 이하에서도 분명한 긴소리를 인정한다.
# In the case of compound words, distinct long sounds are recognized even in the second syllable or later.
#
#     반신반의[반:신바늬/반:신바니]
#     재삼재사[재:삼재사]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a399


# [제6항 붙임 Addendum of Norm 6]
#
# 용언의 단음절 어간에 어미 ‘-아/-어’가 결합되어 한 음절로 축약되는 경우에도 긴소리로 발음한다.
# When a monosyllabic verb stem is combined with the ending ‘-아/-어’ and contracted into a single syllable,
# it is also pronounced as a long sound.
#
#     보아 -> 봐[봐:]
#     기어 -> 겨[겨:]
#     되어 -> 돼[돼:]
#     두어 -> 둬[둬:]
#     하여 -> 해[해:]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a399


# [제6항 붙임 다만 Proviso of Addendum of Norm 6]
#
# ‘오아 -> 와, 지어 -> 저, 찌어 -> 쩌, 치어 -> 처’ 등은 긴소리로 발음하지 않는다.
# Cases such as ‘오아 -> 와, 지어 -> 저, 찌어 -> 쩌, 치어 -> 처’ are not pronounced as long sounds.
#
#     오아 -> 와
#     지어 -> 저
#     찌어 -> 쩌
#     치어 -> 처
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a399


# [제7항 Norm 7]
#
# 긴소리를 가진 음절이라도, 다음과 같은 경우에는 짧게 발음한다.
# Even syllables that normally have long sounds are pronounced short in the following cases.
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a400


# [제7항 1. Norm 7 Item 1]
#
# 1. 단음절인 용언 어간에 모음으로 시작된 어미가 결합되는 경우
# When a monosyllabic verb stem is combined with an ending starting with a vowel
#
#     감다[감:따] — 감으니[가므니]
#     신다[신:따] — 신어[시너]
#     밟다[밥:따] — 밟으면[발브면]
#     알다[알:다] — 알아[아라]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a400


# [제7항 1. 다만 Proviso of Norm 7 Item 1]
#
# 다음과 같은 경우에는 예외적이다.
# The following cases are exceptions (long sounds are maintained).
#
#     끌다[끌:다] — 끌어[끌:러]
#     벌다[벌:다] — 벌어[버:러]
#     없다[업:따] — 없으니[업:쓰니]
#     떫다[떨:따] — 떫은[떨:븐]
#     썰다[썰:다] — 썰어[써:러]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a400


# [제7항 2. Norm 7 Item 2]
#
# 2. 용언 어간에 피동, 사동의 접미사가 결합되는 경우
# When a passive or causative suffix is combined with a verb stem
#
#     감다[감:따] — 감기다[감기다]
#     밟다[밥:따] — 밝히다[발피다]
#     꼬다[꼬:다] — 꼬이다[꼬이다]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a400


# [제7항 2. 다만 Proviso of Norm 7 Item 2]
#
# 다음과 같은 경우에는 예외적이다.
# The following cases are exceptions (long sounds are maintained).
#
#     끌리다[끌:리다]
#     벌리다[벌:리다]
#     없애다[업:쌔다]
#
# Ref:
#   https://korean.go.kr/kornorms/regltn/regltnView.do?regltn_code=0002&regltn_no=346#a400


# [제7항 붙임 Addendum of Norm 7]
#
# 다음과 같은 복합어에서는 본디의 길이에 관계없이 짧게 발음한다.
# In the following compound words, sounds are pronounced short regardless of their original length.
#
#     밀-물
#     썰-물
#     쏜-살-같이
#     작은-아버지
#
