    if os.path.exists(marker_path):
        with open(marker_path, 'r', encoding="utf-8") as f:
            if f.read().strip() == marker_content:
                return

    print("KorNorm: 최초 실행을 감지했습니다. 최적화된 형태소 사전을 빌드합니다...")

